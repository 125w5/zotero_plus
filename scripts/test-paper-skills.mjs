import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const EasySch = {};
const scope = vm.createContext({ EasySch, URL });
for (const file of ['core', 'paper-skills']) vm.runInContext(fs.readFileSync(new URL(`../chrome/content/zotero/xpcom/research/${file}.js`, import.meta.url), 'utf8'), scope);
const sources = [{ id: 'P1-T1', text: 'The sample included 120 participants. Accuracy was 81%.' }];
const section = { heading: 'Result', body: 'The sample comprised 120 participants.', claim_type: 'author_claim', sources: ['P1-T1'], quotes: [{ source_id: 'P1-T1', text: 'The sample included 120 participants.' }] };
const validate = value => EasySch.core.validateResult(JSON.stringify({ sections: [value] }), sources, 'close_read', true);
assert.equal(validate(section).sections[0].verification_status, 'unverified');
assert.throws(() => validate({ ...section, quotes: [{ source_id: 'P1-T1', text: 'Accuracy was 99%.' }] }), /不匹配/);
assert.throws(() => validate({ ...section, sources: ['invented'] }), /不存在/);
assert.throws(() => validate({ ...section, quotes: [] }), /缺少/);
assert.throws(() => validate({ ...section, claim_type: 'verified' }), /区分/);
assert.equal(validate({ ...section, claim_type: 'insufficient_evidence', sources: [], quotes: [] }).sections[0].claim_type, 'insufficient_evidence');
assert.equal(EasySch.core.validateResult(JSON.stringify({ sections: [{ heading: 'Old', body: 'Legacy', sources: [] }] }), [], 'ask').sections.length, 1);
assert.equal(Object.keys(EasySch.paperSkills).length, 12);
const skill = EasySch.getPaperSkill('analyze', { paperSkillOverrides: { close_read: { instruction: 'My instructions', version: 'user-test' } } });
assert.equal(skill.id, 'close_read'); assert.equal(skill.version, 'user-test');
assert.match(EasySch.paperSystemPrompt(skill, {}), /My instructions/);
assert.match(EasySch.paperSystemPrompt(skill, {}), /exact contiguous source text/);
assert.match(EasySch.getPaperSkill('figures_experiments').instruction, /没有图像/);
console.log('Paper skill contracts passed: quote rejection, source binding, legacy compatibility, 12 skills, custom version and capability limits.');
